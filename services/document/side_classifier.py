def score_front_side_features(side_features: dict[str, float]) -> float:
    """Apply the calibrated logistic model to extracted side-layout features."""
    values = np.array(
        [side_features[name] for name in SIDE_FEATURE_NAMES],
        dtype=np.float64,
    )
    logit = float(
        np.dot(
            (values - SIDE_FEATURE_MEANS) / SIDE_FEATURE_SCALES,
            SIDE_FEATURE_WEIGHTS,
        )
        + SIDE_FEATURE_INTERCEPT
    )
    return float(1.0 / (1.0 + np.exp(-np.clip(logit, -30.0, 30.0))))
